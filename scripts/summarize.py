"""Build docs/results.md from outputs/ so every number in the README comes from a run.

    python scripts/summarize.py
"""

import json
from pathlib import Path

import numpy as np

OUT = Path("outputs")


def load(name: str):
    for file in ("results.json", "baselines.json"):
        path = OUT / name / file
        if path.exists():
            return json.loads(path.read_text())
    return None


def final_clients(run: dict) -> list[dict]:
    """Per-client metrics of the last round that produced an evaluation."""
    rounds = [r for r in run["rounds"] if r["clients"]]
    return rounds[-1]["clients"] if rounds else []


def stats(clients: list[dict], suffix: str = "") -> dict:
    r2 = np.array([c[f"r2{suffix}"] for c in clients], float)
    mae = np.array([c[f"mae{suffix}"] for c in clients], float)
    return {"r2": np.nanmedian(r2), "mae": np.median(mae), "good": np.nanmean(r2 > 0.5), "n": len(clients)}


def row(label: str, s: dict | None, extra: str = "") -> str:
    if s is None or s["n"] == 0:
        return f"| {label} | – | – | – | {extra or 'not run'} |"
    return f"| {label} | {s['r2']:.3f} | {s['mae']:.1f} | {s['good']:.0%} | {extra} |"


def section_main(kind: str, prefix: str, unit: str) -> list[str]:
    lines = [f"| Model | Median R² | Median MAE ({unit}) | Clients with R² > 0.5 | Notes |", "|---|---|---|---|---|"]
    base = load(f"{prefix}-baselines")
    local = list(base["local"].values()) if base else []
    central = list(base["centralized"].values()) if base else []
    lines.append(row("Centralized (all data pooled)", stats(central) if central else None, "upper bound, data leaves the clients"))
    lines.append(row("Local only", stats(local) if local else None, "no collaboration"))
    for name, label, note in [
        (f"{prefix}-fedavg", "FedAvg, 2 local epochs", "global model"),
        (f"{prefix}-fedadam", "FedAdam, 2 local epochs", "global model"),
        (f"{prefix}-fedavg-e5", "FedAvg, 5 local epochs", "global model"),
    ]:
        run = load(name)
        if run:  # not every configuration is run for every use case
            lines.append(row(label, stats(final_clients(run)), note))
    for name in (f"{prefix}-fedavg-e5-ft", f"{prefix}-fedavg-ft"):
        run = load(name)
        if not run:
            continue
        clients = final_clients(run)
        lines.append(row("FedAvg, global model", stats(clients), f"same run as next row ({run['config']['local_epochs']} local epochs)"))
        note = "global model fine-tuned locally"
        if base:
            pairs = [(c["mae-ft"], base["local"][c["client"]]["mae"]) for c in clients if c["client"] in base["local"]]
            note += f"; beats local-only for {np.mean([a < b for a, b in pairs]):.0%} of clients"
        lines.append(row("**FedAvg + local fine-tuning**", stats(clients, "-ft"), note))
    return lines


def section_dropout(prefix: str) -> list[str]:
    lines = ["| Setting | Median R² | Median MAE (Wh) | Clients with R² > 0.5 | Rounds that updated the model |",
             "|---|---|---|---|---|"]
    for name, label in [(f"{prefix}-fedavg-e5", "FedAvg, no dropout")] + [
        (f"{prefix}-dropout{d}-{s}", f"{'FaultTolerantFedAvg' if s == 'ftavg' else 'FedAvg'}, {int(float(d) * 100)}% dropout")
        for d in ("0.3", "0.6") for s in ("fedavg", "ftavg")
    ]:
        run = load(name)
        if not run:
            lines.append(row(label, None))
            continue
        updated = f"{sum(1 for r in run['rounds'] if r['train'])}/{len(run['rounds'])}"
        clients = final_clients(run)
        lines.append(row(label, stats(clients), updated) if clients else f"| {label} | – | – | – | {updated} (never evaluated) |")
    return lines


def section_dp(prefix: str) -> list[str]:
    lines = ["| Noise multiplier σ | Median R² | Median MAE (Wh) | Median ε | Worst-client ε |", "|---|---|---|---|---|"]
    for sigma in ("0.0", "0.5", "1.0", "2.0"):
        run = load(f"{prefix}-dp{sigma}")
        if not run:
            continue
        clients = final_clients(run)
        s = stats(clients)
        eps = [c["epsilon"] for c in clients if c.get("epsilon", 0) > 0]
        eps_cols = f"{np.median(eps):.1f} | {max(eps):.1f}" if eps else "– | –"
        lines.append(f"| {sigma if sigma != '0.0' else '0 (no DP)'} | {s['r2']:.3f} | {s['mae']:.1f} | {eps_cols} |")
    return lines


def main() -> None:
    doc = ["# v2 results", "", ("Generated by `scripts/summarize.py` from `outputs/` (one seed per run; "
           "differences of a few hundredths in R² are within run-to-run noise)."), "",
           "## Use case (a): EV energy for a planned 30 s stretch — 50 clients", "",
           *section_main("ev", "ev50", "Wh"), "",
           "## Client dropout: FedAvg vs FaultTolerantFedAvg — 50 EV clients, 40 rounds", "",
           *section_dropout("ev50"), "",
           "## Differential privacy (client-side DP-SGD) — 50 EV clients, 20 rounds, clip 1.0, δ = 1e-4", "",
           *section_dp("ev50"), ""]
    if load("cs-baselines") or load("cs-fedavg-ft"):
        doc += ["## Use case (b): charging-station energy per 15 min — 50 stations", "",
                *section_main("cs", "cs", "Wh per 15 min"), ""]
    Path("docs").mkdir(exist_ok=True)
    Path("docs/results.md").write_text("\n".join(doc))
    print("\n".join(doc))


if __name__ == "__main__":
    main()
